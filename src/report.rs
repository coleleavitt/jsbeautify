//! Triager-ready PoC report generation.
//!
//! The thing that gets a bug-bounty report *accepted* is not prose — it's a
//! reproducible proof a triager can run in under two minutes: the exact request,
//! the observed evidence, and ordered steps. This module turns the artifacts the
//! pipeline already produces (findings, correlated [`AttackChain`]s, and live
//! [`Validation`] verdicts) into a self-contained Markdown report with copyable
//! `curl` commands and a clear impact statement.
//!
//! It is deliberately *evidence-first*: a finding with no live confirmation is
//! reported as **unconfirmed** (a lead to verify), while a confirmed validation
//! carries its proof. This is the antidote to confident-but-false AI findings —
//! the report never claims impact it didn't observe.

#![allow(clippy::doc_markdown)]

use std::fmt::Write as _;

use crate::analyzers::match_kind::AnalyzerMatch;
use crate::chains::AttackChain;

/// Append a line to a Markdown buffer. Writing to a `String` is infallible, so
/// this swallows the always-`Ok` `fmt::Result` in one audited place rather than
/// scattering `let _ =` at every call site.
macro_rules! line {
    ($buf:expr, $($arg:tt)*) => {{
        let _ = writeln!($buf, $($arg)*);
    }};
}

/// One validated probe, pairing a finding/target with its live verdict.
#[derive(Debug, Clone)]
pub struct ProbeEvidence {
    /// The kind of finding probed (e.g. `open_redirect`).
    pub finding_kind: String,
    /// The concrete URL/target that was probed.
    pub target: String,
    /// Verdict string (`CONFIRMED` / `refuted` / `inconclusive`).
    pub verdict: String,
    /// Human evidence (the observed `Location`, reflected canary, …).
    pub evidence: String,
    /// The exact request line a triager can replay, if known.
    pub repro: Option<String>,
}

/// Map a finding kind to a short CWE/OWASP impact sentence for the report.
fn impact_line(kind: &str) -> &'static str {
    match kind {
        "dom_xss" => {
            "Cross-site scripting (CWE-79): attacker-controlled input reaches a JS sink, enabling script execution in a victim's session."
        }
        "open_redirect" => {
            "Open redirect (CWE-601): the application redirects to an attacker-controlled URL, enabling phishing or token theft."
        }
        "idor_candidate" => {
            "Insecure Direct Object Reference (CWE-639): an object is addressed by a client-supplied id, suggesting missing object-level authorization."
        }
        "high_entropy_secret" => {
            "Hard-coded credential (CWE-798): a high-entropy secret is embedded in client-side code."
        }
        "known_cve" => "Vulnerable dependency (CWE-1035): the page ships a library version with a known CVE.",
        "proto_pollution" => {
            "Prototype pollution (CWE-1321): an unsafe property write with an attacker-controlled key can corrupt Object.prototype."
        }
        _ => "Potential security weakness; verify impact against the target.",
    }
}

/// Build a `curl` reproduction line for a probe target (best-effort).
#[must_use]
pub fn curl_for(kind: &str, target: &str) -> String {
    match kind {
        // Open redirect / IDOR: a plain GET, show response headers (-i).
        "open_redirect" | "idor_candidate" => format!("curl -ski '{target}'"),
        // known_cve: fetch the asset and confirm the version banner.
        "known_cve" => format!("curl -sk '{target}' | head -c 400"),
        // dom_xss reflection + default: a plain GET (grep the response for the canary).
        _ => format!("curl -sk '{target}'"),
    }
}

/// Render a full Markdown PoC report.
///
/// `findings` are all analyzer findings, `chains` the correlated attack paths,
/// and `evidence` the live-probe results (may be empty when `--validate` wasn't
/// run). The report leads with confirmed chains/probes, then unconfirmed leads.
#[must_use]
pub fn render_markdown(
    target_label: &str,
    findings: &[AnalyzerMatch],
    chains: &[AttackChain],
    evidence: &[ProbeEvidence],
) -> String {
    let mut md = String::new();
    line!(md, "# Security report — {target_label}\n");

    let confirmed: Vec<&ProbeEvidence> = evidence.iter().filter(|e| e.verdict == "CONFIRMED").collect();
    render_summary(&mut md, findings, chains, &confirmed, evidence.is_empty());
    render_chains(&mut md, chains);
    render_confirmed(&mut md, &confirmed);
    render_unconfirmed(&mut md, evidence);
    render_findings_table(&mut md, findings);

    md.push_str(
        "---\n_Generated by js-beautify-rs. Confirmed items were probed against an authorized, in-scope target._\n",
    );
    md
}

fn render_summary(
    md: &mut String,
    findings: &[AnalyzerMatch],
    chains: &[AttackChain],
    confirmed: &[&ProbeEvidence],
    no_validation: bool,
) {
    line!(md, "## Summary\n");
    line!(
        md,
        "- {} finding(s), {} correlated attack chain(s), {} live-confirmed probe(s).",
        findings.len(),
        chains.len(),
        confirmed.len()
    );
    if confirmed.is_empty() {
        line!(
            md,
            "- No findings were live-confirmed{}. Items below are leads to verify, not proven impact.",
            if no_validation { " (validation not run)" } else { "" }
        );
    }
    md.push('\n');
}

fn render_chains(md: &mut String, chains: &[AttackChain]) {
    if chains.is_empty() {
        return;
    }
    line!(md, "## Attack chains\n");
    for (n, c) in chains.iter().enumerate() {
        line!(md, "### Chain {}: {} (score {}, {})\n", n + 1, c.kind, c.score, c.cwe);
        line!(md, "{}\n", c.title);
        line!(md, "Steps:\n");
        for (i, step) in c.steps.iter().enumerate() {
            line!(
                md,
                "{}. **{}** — `{}`: `{}`",
                i + 1,
                step.role,
                step.match_kind,
                truncate(&step.match_value, 100)
            );
        }
        md.push('\n');
    }
}

fn render_confirmed(md: &mut String, confirmed: &[&ProbeEvidence]) {
    if confirmed.is_empty() {
        return;
    }
    line!(md, "## Confirmed findings (reproducible)\n");
    for (n, e) in confirmed.iter().enumerate() {
        line!(md, "### {}. {} — CONFIRMED\n", n + 1, e.finding_kind);
        line!(md, "**Impact:** {}\n", impact_line(&e.finding_kind));
        line!(md, "**Target:** `{}`\n", e.target);
        line!(md, "**Evidence:** {}\n", e.evidence);
        let repro = e.repro.clone().unwrap_or_else(|| curl_for(&e.finding_kind, &e.target));
        line!(md, "**Reproduce:**\n\n```sh\n{repro}\n```\n");
    }
}

fn render_unconfirmed(md: &mut String, evidence: &[ProbeEvidence]) {
    let unconfirmed: Vec<&ProbeEvidence> = evidence.iter().filter(|e| e.verdict != "CONFIRMED").collect();
    if unconfirmed.is_empty() {
        return;
    }
    line!(md, "## Unconfirmed leads (verify manually)\n");
    for e in unconfirmed {
        line!(
            md,
            "- `{}` at `{}` — {} ({})",
            e.finding_kind,
            e.target,
            e.evidence,
            e.verdict
        );
    }
    md.push('\n');
}

fn render_findings_table(md: &mut String, findings: &[AnalyzerMatch]) {
    if findings.is_empty() {
        return;
    }
    line!(md, "## Static findings\n");
    line!(md, "| kind | severity | CWE | value |");
    line!(md, "|---|---|---|---|");
    for f in findings.iter().take(100) {
        let cwe = f
            .metadata
            .as_ref()
            .and_then(|m| m.get("cwe"))
            .and_then(serde_json::Value::as_str)
            .unwrap_or("-");
        line!(
            md,
            "| {} | {:?} | {} | `{}` |",
            f.match_kind,
            f.severity,
            cwe,
            truncate(&f.match_value, 60).replace('|', "\\|")
        );
    }
    md.push('\n');
}

fn truncate(s: &str, n: usize) -> String {
    if s.chars().count() <= n {
        s.to_string()
    } else {
        let t: String = s.chars().take(n).collect();
        format!("{t}…")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::analyzers::match_kind::{FileType, PositionRange, Provenance};
    use crate::analyzers::regex_bank::Severity;
    use crate::chains::{AttackChain, ChainStep};

    fn finding(kind: &str, value: &str) -> AnalyzerMatch {
        AnalyzerMatch::new(
            kind,
            value,
            PositionRange::new(1, 0, 1, 1),
            FileType::Js,
            Some("https://app.target.com/a.js".into()),
        )
        .with_provenance(Provenance::Ast)
        .with_severity(Severity::High)
        .with_metadata(serde_json::json!({ "cwe": "CWE-79" }))
    }

    #[test]
    fn curl_lines_match_kind() {
        assert!(curl_for("open_redirect", "https://t/x").contains("-ski"));
        assert!(curl_for("dom_xss", "https://t/x").starts_with("curl -sk"));
    }

    #[test]
    fn report_leads_with_confirmed_evidence() {
        let findings = vec![finding("open_redirect", "location.href=u")];
        let chains = vec![AttackChain {
            kind: "account_takeover".into(),
            title: "Open redirect can exfiltrate a token".into(),
            steps: vec![ChainStep {
                finding_index: 0,
                role: "exfil-vector",
                match_kind: "open_redirect".into(),
                match_value: "location.href=u".into(),
            }],
            score: 70,
            cwe: "CWE-601",
        }];
        let evidence = vec![ProbeEvidence {
            finding_kind: "open_redirect".into(),
            target: "https://app.target.com/go?redirect=//evil".into(),
            verdict: "CONFIRMED".into(),
            evidence: "redirects off-origin to attacker host evil (HTTP 302)".into(),
            repro: None,
        }];

        let md = render_markdown("app.target.com", &findings, &chains, &evidence);
        assert!(md.contains("# Security report — app.target.com"));
        assert!(md.contains("## Attack chains"));
        assert!(md.contains("Confirmed findings (reproducible)"));
        assert!(md.contains("curl -ski")); // repro command present
        assert!(md.contains("CWE-601"));
        assert!(md.contains("1 live-confirmed probe"));
    }

    #[test]
    fn report_marks_unconfirmed_when_no_confirmation() {
        let findings = vec![finding("dom_xss", "el.innerHTML=u")];
        let md = render_markdown("t", &findings, &[], &[]);
        assert!(md.contains("validation not run"));
        assert!(md.contains("not proven impact"));
    }
}
