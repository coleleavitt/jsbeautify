use super::super::match_kind::{AnalyzerMatch, FileType, PositionRange, Provenance};
use super::super::regex_bank::Severity;
use super::patterns::{
    BASE_QUERY_RE, BUILDER_PARAM_RE, CORE_RE, ENDPOINT_RE, MARKER_RE, REDUCER_PATH_RE, SLICE_RE, STRING_LIT_RE,
    TAG_TYPES_RE, THUNK_RE,
};

struct QueryContext<'a> {
    reducer_path: Option<String>,
    tags: Vec<String>,
    base_url: Option<String>,
    builder_params: Vec<&'a str>,
}

fn query_context(source: &str) -> QueryContext<'_> {
    let multiple_apis = REDUCER_PATH_RE.find_iter(source).count() > 1 || BASE_QUERY_RE.find_iter(source).count() > 1;
    let (reducer_path, tags, base_url) = if multiple_apis {
        (None, Vec::new(), None)
    } else {
        let tags = TAG_TYPES_RE
            .captures(source)
            .and_then(|c| c.get(1))
            .map_or_else(Vec::new, |m| {
                STRING_LIT_RE
                    .captures_iter(m.as_str())
                    .filter_map(|c| c.get(1))
                    .map(|x| x.as_str().to_string())
                    .collect()
            });
        (
            capture_first(source, &REDUCER_PATH_RE),
            tags,
            capture_first(source, &BASE_QUERY_RE),
        )
    };
    let builder_params = BUILDER_PARAM_RE
        .captures_iter(source)
        .filter_map(|c| c.get(1))
        .map(|m| m.as_str())
        .collect();

    QueryContext {
        reducer_path,
        tags,
        base_url,
        builder_params,
    }
}

fn capture_first(source: &str, re: &regex::Regex) -> Option<String> {
    re.captures(source)
        .and_then(|c| c.get(1))
        .map(|m| m.as_str().to_string())
}

/// Scan `source` for Redux / RTK / RTK Query signatures.
///
/// # Panics
///
/// Panics only if a compile-time regex pattern is invalid.
#[must_use]
pub fn analyze(source: &str, file_path: Option<&str>, file_type: FileType) -> Vec<AnalyzerMatch> {
    let mut out = Vec::new();
    let fp = || file_path.map(str::to_string);

    // --- redux_core: reserved action types + prod-error URL ---------------
    for caps in CORE_RE.captures_iter(source) {
        let whole = caps.get(0).unwrap();
        let val = caps.get(1).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "redux_core",
                val,
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info),
        );
    }

    // --- rtk_marker: internal Symbol.for() tags ---------------------------
    for caps in MARKER_RE.captures_iter(source) {
        let whole = caps.get(0).unwrap();
        let val = caps.get(1).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "rtk_marker",
                val,
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info),
        );
    }

    // --- rtk_slice: createSlice({name,reducers}) --------------------------
    // Action types generated by RTK follow `${slice}/${reducerKey}`
    // (createSlice.ts line 559), so we surface the slice name + action prefix.
    for caps in SLICE_RE.captures_iter(source) {
        let whole = caps.get(0).unwrap();
        let name = caps.get(1).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "rtk_slice",
                name.clone(),
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info)
            .with_metadata(serde_json::json!({
                "slice": name,
                "action_prefix": format!("{name}/"),
            })),
        );
    }

    // --- rtk_async_thunk: createAsyncThunk("prefix") ----------------------
    for caps in THUNK_RE.captures_iter(source) {
        let whole = caps.get(0).unwrap();
        let prefix = caps.get(1).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "rtk_async_thunk",
                prefix.clone(),
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info)
            .with_metadata(serde_json::json!({
                "type_prefix": prefix,
                "action_types": [
                    format!("{prefix}/pending"),
                    format!("{prefix}/fulfilled"),
                    format!("{prefix}/rejected"),
                ],
            })),
        );
    }

    let query = query_context(source);

    // --- rtk_query_api: fetchBaseQuery({baseUrl}) -------------------------
    for caps in BASE_QUERY_RE.captures_iter(source) {
        let whole = caps.get(0).unwrap();
        let url = caps.get(1).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "rtk_query_api",
                url.clone(),
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info)
            .with_metadata(serde_json::json!({
                "base_url": url,
                "reducer_path": query.reducer_path.clone(),
                "tags": query.tags.clone(),
            })),
        );
    }

    // --- rtk_query_endpoint: <builder>.query / <builder>.mutation ---------
    for caps in ENDPOINT_RE.captures_iter(source) {
        let builder = caps.get(2).map_or("", |m| m.as_str());
        // Only trust matches whose receiver is the real RTK Query builder param;
        // this rejects unrelated `key: obj.query(` (DB clients, query builders).
        if !query.builder_params.contains(&builder) {
            continue;
        }
        let whole = caps.get(0).unwrap();
        let name = caps.get(1).map_or("", |m| m.as_str()).to_string();
        let kind = caps.get(3).map_or("", |m| m.as_str()).to_string();
        out.push(
            AnalyzerMatch::new(
                "rtk_query_endpoint",
                name.clone(),
                PositionRange::from_byte_range(source, whole.start(), whole.end()),
                file_type,
                fp(),
            )
            .with_provenance(Provenance::Other)
            .with_severity(Severity::Info)
            .with_metadata(serde_json::json!({
                "endpoint": name,
                "endpoint_type": kind,
                "base_url": query.base_url.clone(),
                "reducer_path": query.reducer_path.clone(),
                "tags": query.tags.clone(),
            })),
        );
    }

    out
}
